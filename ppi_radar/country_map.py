# Русские названия, которые уже канон — проходят как есть (в т.ч. те,
# что зашиты в headless-парсерах).
_RU_CANON = set(_EN_TO_RU.values())

_warned: set[str] = set()


def normalize_country(raw: str) -> str:
    if not raw:
        return raw
    stripped = raw.strip()
    if stripped in _RU_CANON:
        return stripped
    canon = _EN_TO_RU.get(stripped.lower())
    if canon:
        return canon
    if stripped not in _warned:
        _warned.add(stripped)
        print(f"  (страна '{stripped}' не найдена в таблице нормализации — оставляю как есть, "
              f"проверьте ppi_radar/country_map.py)")
    return stripped
